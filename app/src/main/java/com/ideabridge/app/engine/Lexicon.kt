package com.ideabridge.app.engine

/**
 * قوائم إشارات صريحة وقابلة للتعديل تستند إليها قواعد نوع الرابط. الكلمات بصيغتها الموحدة
 * (بلا "ال"، والتاء المربوطة مكتوبة هاءً لأن المطابقة تتم بعد cueKey).
 * لا يُصنَّف رابط على أنه سبب أو مشكلة/حل إلا إذا ظهرت إشارة صريحة من هذه القوائم في نص الملاحظة.
 */
internal object Lexicon {
    val PROBLEM = setOf(
        "مشكله", "مشاكل", "صعوبه", "صعوبات", "هدر", "اهدار", "تلف", "ضياع", "خساره", "خسائر", "نقص",
        "تاخر", "تاخير", "بطء", "فوضي", "عجز", "فقدان", "تعثر", "ازمه", "عقبه",
    )
    val SOLUTION = setOf("حل", "حلول", "تطبيق", "تطبيقات", "اداه", "ادوات", "نظام", "انظمه", "منصه", "برنامج", "برامج", "اتمته")
    val CAUSE = setOf("سبب", "يسبب", "تسبب", "يؤدي", "تؤدي", "يودي", "تودي", "ادي")
    val EFFECT = setOf("نتيجه", "ينتج", "تنتج", "بسبب", "ناتج")

    /** يوحّد التاء المربوطة مع الهاء لأغراض مطابقة الإشارات فقط. */
    fun cueKey(term: String): String = term.replace('ة', 'ه')
}
